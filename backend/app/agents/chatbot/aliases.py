_STRIP_CHARS = re.compile(r"[\s\-_,·()\[\]/]+")


def normalize_name(raw: str) -> str:
    return _STRIP_CHARS.sub("", raw.strip().lower())


# CAS번호 형식: 2~7자리-2자리-1자리 (예: 71-43-2, 68476-33-5)
CAS_PATTERN = re.compile(r"^\d{2,7}-\d{2}-\d$")


def looks_like_cas(raw: str) -> bool:
    return bool(CAS_PATTERN.match(raw.strip()))


