"""필요 여유수심(UKC, Under Keel Clearance) 규칙 — 판정·대체안·대시보드가 함께 쓰는 한 기준.

    필요 여유 = max(UKC_MIN_M, 흘수 × UKC_RATIO) = max(1.0m, 흘수 10%)

[2026-09-27] 예전엔 기준이 둘이었다 — 판정 잡은 고정 1.0m(스케줄링 설계문서의 기본값,
출처 없음), 대시보드 흘수 점검 뷰는 흘수의 10%(뷰 주석: "통상 관행값, 법정 수치 아님").
어느 쪽도 확정 근거가 없어 **여유가 흡수해야 하는 오차**로 정했다.
  · 배 크기와 무관한 고정 오차 — 측심 오차·해저 기복·조위 예보 오차(실측 22cm, 14번
    문서) → 작은 배에도 하한이 필요하다(흘수 5m 의 10% = 0.5m 는 조위 오차 하나로 절반).
  · 배 크기에 비례하는 오차 — AIS 흘수는 트림을 반영하지 않아 실제 최대 흘수가 더 클 수
    있고(대시보드 뷰 주석), 선체 운동도 배가 클수록 크다 → 큰 배는 비율로 늘려야 한다.
max 는 두 옛 기준 어느 것보다도 느슨하지 않다. 흘수 10m 미만은 1.0m, 이상은 10% 가 된다.
적용 시점(9/27) 접안선 45척에서 판정이 바뀐 배는 0척이었다.

이 값도 임시 기준이다 — 울산항 터미널 운영규정을 확보하면 이 두 상수만 바꾼다.
대시보드 뷰(mart.berth_draught_check · berth_audit)는 SQL 이라 같은 식을 따로 갖고 있다.
두 곳이 어긋나면 tests/test_ukc_rule_20260927.py 가 실패한다.
"""

UKC_MIN_M = 1.0
UKC_RATIO = 0.10


def required_ukc_m(draught_m: float) -> float:
    """이 흘수의 배가 선체 아래에 남겨야 할 최소 여유(m)."""
    return max(UKC_MIN_M, UKC_RATIO * draught_m)
